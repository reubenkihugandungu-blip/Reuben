// DEFINITION
// JavaScript is a programming language that runs inside a web browser. 
// Unlike Python, which runs on a server, JavaScript runs on the user's device. 
// It can read and change anything on a web page, respond to clicks and keyboard events, and make requests to external APIs.

// Known example:
// A phone repair shop's website. The HTML is the shop layout: shelves, counter, chairs.
// The CSS is the paint, lighting, signage. JavaScript is the staff. When a customer clicks "Get a Quote,"
// JavaScript reads the form values, validates them, and shows a result without reloading the page.
// The shop does not close and reopen. It just responds.

// Python and JavaScript solve similar problems with different syntax.
// The core concepts (variables, loops, functions, conditionals) are the same. 
// The differences are mostly in how you write them.

