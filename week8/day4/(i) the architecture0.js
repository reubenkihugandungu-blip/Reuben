// CONNECTING JS TO A PYTHON BACKEND
// JavaScript runs in the browser. Python runs on a server.
//  A REST API is the contract between them. JavaScript sends requests; Python processes and responds.

// Definition: Full-stack
// A full-stack application has a front end (what the user sees in the browser) and a back end (logic and data running on a server). 
// JavaScript handles the front end. Python handles the back end. They communicate via HTTP using JSON.

// Known example: A phone repair shop with a front counter (JavaScript) and a back workshop (Python). 
// The customer never enters the workshop.
// The counter staff (JS) takes the request, passes it through a window to the workshop (Python), and brings back the result.
// JSON is the paper slip they write the order and response on.