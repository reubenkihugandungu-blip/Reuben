# Project-BASED pricing
# A fixed fee for a defined deliverable. The client knows the total cost upfront. You know exactly what you are building.
#  Risk: scope creep. Protection: a written brief with clear deliverables before work begins.

# Definition: Hourly pricing
# A rate per hour billed against actual time spent. Common for consulting, maintenance, or open-ended projects.
# Risk: clients who do not understand why something takes time. Protection: a weekly or daily update on hours logged.

# Definition: Retainer pricing
# A fixed monthly fee for ongoing availability and work. The client buys a block of your time or attention each month.
#  Predictable income. Common for maintenance contracts, monthly reporting, or continuous development.

# Model	                              Best for	                                     Risk to manage
# Project-based	         Defined builds: a script, an API, a dashboard	              Scope creep
# Hourly	             Consulting, debugging, open-ended work	                      Client surprise at invoice
# Retainer	             Ongoing maintenance, monthly reports, support	             Under-delivering on the block