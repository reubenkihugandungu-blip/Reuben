# Scenario	                                       Response
# "That's too expensive"	Ask what budget they have. If it is below your floor, explain what you can deliver at that
#                            budget. If it is too low, it is not your client.
# "Can you do it cheaper?"	Reduce the scope, not the rate. Remove a feature, a revision, or a component. 
#                           Same hourly rate, smaller project.
# "What's your hourly rate?"	Give a range ($35-55/h). Then immediately offer a project price so they have a concrete
#                                number to evaluate instead of doing mental math.
# Silence after quote	    Wait. Do not discount before they respond. Silence is not rejection. It is decision-making.
# "We'll use you for everything"	Agree only to what is in writing with a defined scope.
#                                   Vague promises of future work are not retainers.

# Tip:
#  Quote confidently in writing, not verbally. 
# Send a short proposal document: client name, project scope, deliverables, timeline, price, and payment terms. 
# One page is enough. It shows you are professional and removes the ambiguity that causes disputes later.
