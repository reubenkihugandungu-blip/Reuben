# Three inputs determine your starting price: 
# the value of the outcome to the client, 
# what comparable work costs on platforms like Upwork and Fiverr, and how long the work actually takes you to complete.

# Known example:
#  A phone repair technician setting screen replacement prices.
#  They look at what the broken screen costs the customer in productivity (value),
#  what other local shops charge (market), and how long the job takes them (cost). 
# They set a price between market rate and their true cost, then adjust after the first ten jobs based on demand.
# Developer pricing works the same way.

# Starter Pricing Tiers
## Tier 1: Quick Automation Script
# $150 to $400
# A single Python script that automates one task. Data cleaning, report generation, a simple API call.
#  Deliverable: working script with README. Timeline: 1 to 3 days.

## Tier 2: Data Pipeline or API Integration
# $400 to $1,000
# A multi-part project connecting two tools or processing data from multiple sources.
#  Deliverable: script, documentation, one revision. Timeline: 3 to 7 days.

## Tier 3: Full Tool or Dashboard
# $1,000 to $3,000
# A deployed application with a front end, back end, and database.
#  Includes a live URL, documentation, and two weeks of post-launch support. Timeline: 2 to 4 weeks.

## Monthly Retainer
# $300 to $800 / month
# Ongoing maintenance, monthly reports, feature additions, or technical support.
#  Defined scope per month. Cancellable with 30 days' notice.

# Note: These are starting ranges, not ceilings.
#  As you build a track record and serve clients who have larger problems, prices go up. 
# The first project is not about maximizing revenue. It is about proving the system works and getting a testimonial.
