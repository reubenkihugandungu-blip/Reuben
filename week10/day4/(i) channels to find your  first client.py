# 1. Your existing network (highest probability)
# WhatsApp contacts, LinkedIn connections, former colleagues, classmates. Message five people specifically.
# Tell them what you build, who you help, and ask if they know anyone with that problem. Do not post generally. 
# Message specifically.

## 2. X (Twitter) content and direct messages
# Post short demonstrations of tools you built. A short video of a script running. A before/after of a data cleanup. 
# Share the output, not the code. Clients do not read code. They read results. Direct message people who engage.

## 3. LinkedIn outreach
# Connect with operations managers, small business owners, and founders in industries where automation saves
#  time (logistics, e-commerce, hospitality, health). Send a specific message, not a template. 
#  Reference something specific about their business.

## 4. Freelance platforms (Upwork, Fiverr, Contra)
# Set up profiles with clear service offers. Apply to five to ten jobs per week.
#  Write proposals that reference the specific problem in the post, not a generic pitch. 
# The first job on a platform is the hardest because there are no reviews. Price slightly lower for the first
# job to get the review, then raise.

## 5. Local businesses
# Every local business with a spreadsheet has an automation problem they do not know can be solved. 
# Walk in, introduce yourself as a developer who automates data tasks, 
# and ask if they have anything they do manually that takes too much time. Many will.
# Most will not know it can be automated.