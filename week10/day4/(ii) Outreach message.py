# A good outreach message has four parts: a specific observation about them, the problem you solve, a concrete
#  example or result, and a low-friction next step. It is short. It is not about you. It ends with a question, 
# not a pitch.

# LinkedIn Direct Message
# Hi [Name],

# I noticed your team is hiring a data analyst on LinkedIn.
# That usually means there is more data to process than current capacity allows.
# I build Python automation tools that handle data cleaning, report generation, and API integrations. 
# One script I recently delivered reduced a client's weekly reporting from two hours to under five minutes.

# Would it make sense to have a quick call to see if automation could handle some of what you are looking to hire for?

# Brian

# Tip: The message above works because it is specific (a hiring signal), 
# not generic ("I am a Python developer looking for opportunities"). Every word earns its place.
#  Remove the words "I am passionate about" and "would love to" and replace them with evidence and a clear question.