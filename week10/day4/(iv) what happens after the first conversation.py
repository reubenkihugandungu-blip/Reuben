# What Happens After the First Conversation
# Stage	                              What to do	                                           What not to do
# Discovery call	Ask questions. Listen. Understand their actual problem.         	 Pitch before you understand
# Proposal	      Send a one-page written scope with price and timeline within 24 hours	     Give a verbal quote and wait
# Negotiation	Reduce scope, not rate. Explain what each price point includes.	          Discount without changing scope
# Contract	       A written agreement, even one paragraph, 
#                 with deliverables, timeline, price, and payment terms	                Start work without written confirmation
# Delivery	     Deliver on time. Send a final handover message with instructions.	    Disappear after sending files
# Testimonial	Ask for a written testimonial within one week of delivery	           Wait months and hope they remember

# Note: The testimonial is as important as the project itself.
#  A single written testimonial with a specific outcome ("Brian's script saved our team 3 hours per week")
#  is worth ten times a generic one ("Great developer, highly recommend"). 
# Ask for it immediately after a successful delivery, before the client moves on to their next problem.

# Local market note: In Kenya, the warm network works faster than cold outreach.
#  A Jua Kali craftsman who builds a job tracker for his own workshop and shows it 
# to three neighboring shop owners has done more sales work than ten cold DMs to strangers. 
# Build the tool. Use it. Let people see it working. The referral follows without a pitch.
