# What to leave out                                                            	Why
# Incomplete or broken projects                 	A broken demo signals unreliability faster than any explanation
# Tutorial projects with no modification	        Cloned code shows you can follow directions. Not that you can build.
# Projects without a README	                        Undocumented code looks abandoned
# More than six projects	                        Dilutes the strongest work. Quality over quantity.
# Skills lists without proof	                    "I know Python" means nothing. A Python project means everything.

# Note:
#  If you only have one or two solid projects right now, that is enough to start.
#  One finished, documented, working project with a clear README is more compelling than ten unfinished ones.
#  Build the portfolio incrementally as you complete more work.