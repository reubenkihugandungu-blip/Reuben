# Platform	                           Best for	                                                                Cost
# GitHub Pages	      Static HTML/CSS portfolio, free hosting from a GitHub repo	                             Free
# Vercel	          React or Next.js portfolio, auto-deploys from GitHub	                           Free tier available
# Render	           Python/FastAPI backend + static front end together	                           Free tier available
# Notion	           Quick portfolio page without code, shareable link	                           Free
# Custom domain	       Professional presence (e.g., brianotieno.dev)	                               ~$10-15/year

# Tip:
# For a GitHub Pages portfolio, create a repo named username.github.io.
#  Push an index.html file to the main branch.
#  GitHub automatically serves it at https://username.github.io. No server, no cost, live in under five minutes.

# Note:
#  Your first client may be a dairy farmer, a Jua Kali workshop owner, or a school administrator who has never heard of 
