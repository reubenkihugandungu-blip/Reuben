# Where to Put Your Service Offer

# Location	                             Format	                                                      Length
# LinkedIn headline   	       One sentence: "Python automation for [client type]"              	    Under 120 characters
# Portfolio site hero	        Header + one sentence + call to action button	                        Under 20 words
# GitHub profile README	       Two to three bullet points listing specific services	                Under 50 words
# Proposal or outreach message.	Full offer: client, problem, outcome, tools, proof	                One paragraph
# Upwork or freelance platform profile.	First 300 characters must carry the core offer	           Start with the outcome

# Tip:
#  Write your service offer in the second-person perspective on your portfolio site and in the 
# first-person perspective in outreach messages. "You need X, I deliver Y" works for a landing page.
#  "I help clients who need X by delivering Y" works in a direct message or proposal.

# Note:
#  The formula works for any local market. "I help Jua Kali workshops that lose track of pending jobs
#  by building a simple Python job tracker they can run on any laptop" is a complete service offer.
#  "I help dairy cooperatives that record milk yields by hand by automating their weekly report into a one-click script"
#  is another. Same structure. 
# Different domain. Start with the client you already know.