# A service offer is a specific, outcome-focused statement that tells a potential client exactly what they get when they hire you. 
# It is different from a skill list.
#  A skill is what you know. A service is what you deliver.

# Service offer (specific outcome)
# "I build Python automation scripts that pull data from multiple sources, clean it, and produce a weekly summary
#  report automatically."

# The formula is simple. Making it specific is the work. Every generic word in a service offer costs you a client. 
# "Businesses" is worse than "small e-commerce stores." "Improve their data" is worse than "reduce manual reporting
# time from two hours to five minutes."

# Generic version	                                               Specific version
# I help businesses with Python      I help logistics companies automate their weekly shipment reconciliation reports using Python and pandas
# I build APIs	                     I build FastAPI backends that connect to Supabase and serve data to a web dashboard
# I do data analysis	             I clean and analyze sales or operational data from CSV exports and produce a structured summary with key metrics
# I build AI tools	                 I build Python scripts that call the OpenAI API to automate first-draft responses for customer support teams