# Command	                                   Purpose
# git remote add origin URL	                  Link local repo to GitHub
# git remote -v	                              Show configured remotes
# git push -u origin main	                  First push (sets upstream)
# git push	                                  Push current branch to remote
# git pull	                                  Download and merge remote changes
# git fetch	                                  Download remote changes without merging
# git clone URL	                              Download a full remote repo
# git push -u origin branch	                  Push a new branch to GitHub

# Same Concept, Different Context: GitHub is the offsite backup. 
# The same way M-Pesa records a transaction on Safaricom's servers even if your phone is lost or stolen,
#  your code on GitHub is safe even if your laptop fails.
#  git push sends your commits to that remote backup. git pull brings changes back to your machine.
#  Push consistently: every working session should end with a push.
