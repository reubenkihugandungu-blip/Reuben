# Command	                      Purpose
# git branch	List all local branches
# git branch name	Create a new branch
# git switch name	Switch to an existing branch
# git switch -c name	Create and switch in one command
# git merge branch-name	Merge named branch into current branch
# git branch -d name	Delete a merged branch
# git branch -D name	Force-delete (even if unmerged)
# git log --oneline --graph	Visual branch history

# Same Concept, Different Context:
#  A Jua Kali craftsman testing a new gate hinge design sketches it in a separate notebook before adopting
#  it on client jobs. That notebook is a branch. If the design works, it merges into the main workflow.
#  If not, the notebook is closed and discarded.
#  The main process stays untouched throughout. git branch creates the notebook. git merge adopts the design. 
# git branch -d discards it.