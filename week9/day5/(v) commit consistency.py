# The GitHub contribution graph (the green squares on your profile) shows daily commit activity.
#  Clients and recruiters look at it.
#  A consistent pattern of small daily commits is more compelling than three huge commits once a month.

# Habit	                                              What it produces on GitHub
# One commit per working session	                  Consistent green squares on the activity graph
# Descriptive commit messages	                      Readable history that shows your thinking
# Feature branches + PRs	                          A network graph showing disciplined development workflow
# Updated READMEs	                                  Projects that look maintained and professional
# Public repos (not all private)	                  Work that is visible to anyone who searches for you

# Tip: Commit early and often.
#  A commit message that says "Work in progress: add API endpoint skeleton" is fine.
#  It is better than not committing. The history shows you were working. 
# You can always clean up messages later with git rebase -i before a final push.

