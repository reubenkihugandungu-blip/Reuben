# Definition

# git init creates a new Git repository inside the current folder.
#  It adds a hidden .git folder that stores all version history. 
# This command turns a regular folder into a Git-tracked project.

# Terminal: Create and initialize a project
# Create a new project folder
# mkdir smp-tracker
# cd smp-tracker

# Initialize Git
# git init
# Initialized empty Git repository in /home/brian/smp-tracker/.git/

# Check the status (nothing tracked yet)

# git status
# On branch main

# No commits yet

# nothing to commit (create/copy files and use "git add" to track)
# Note: git init creates the repository. It does not create a commit.
#  The repository is empty until you add files and commit them. git status is the command you will use most frequently.
