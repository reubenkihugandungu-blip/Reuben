# A list is a collection of values stored in order.
#  You create a list using square brackets [ ] with items separated by commas.
#  Each item has a position number called an index, and that index starts at 0, not 1.
# index 0 is 8 glasses of water

daily_habits = ["8 glasses water", "8000 steps", "cold shower", "OMAD FAST", "workout"]
print(daily_habits)

# How to access the first item in a list.
print(daily_habits[0])
print(daily_habits[1])
print(daily_habits[2])

