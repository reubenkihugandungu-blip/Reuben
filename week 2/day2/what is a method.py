# A method is a function attached to a specific type of data.
#  You call it with a dot: list_name.method_name(). List methods modify the list directly.
#  After calling one, the list itself changes.
# append(x)	Add item x to the end of the list
# insert(i, x)	Add item x at position i
# remove(x)	Remove the first occurrence of item x
# pop(i)	Remove and return item at position i (default: last item)
# sort()	Sort the list in ascending order
# reverse()	Reverse the order of the list
# index(x)	Return the position of item x
# count(x)	Count how many times item x appears