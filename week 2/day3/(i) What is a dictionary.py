# A dictionary is a collection of labelled data.
#  Each piece of data has a name (called a key) and a value. 
# You look up data using the key, not a position number.

# A dictionary stores data as key-value pairs. 
# You create one using curly braces { }. Each key is followed by a colon and its value. 
# Keys must be unique. Values can be any data type.

daily_log = {
    "steps": 9200,
    "water_glasses": 8,
    "cold_shower": True,
    "fasting_protocol": "OMAD",
    "sleep_hours": 7.5
}
print(daily_log)
