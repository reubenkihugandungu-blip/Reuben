# When Python encounters something it cannot execute, it raises an exception. 
# This is Python's way of saying something went wrong. If you do not handle it, the program 
# stops immediately and shows an error message.

# An exception is an error that occurs while a program is running. Common ones are ValueError 
# (wrong type of value), ZeroDivisionError (dividing by zero), KeyError (key not in dictionary),
#  and FileNotFoundError (file does not exist).
#  Python handles all exceptions the same way: with try and except.