# Two operators that beginners often do not know about but use constantly once they learn them:

# Operator	Name	What it does	Example	Result
# //	Integer division	Divides and drops the decimal	65000 // 7	9285
# %	Modulo (remainder)	Returns what is left over after dividing	10 % 3	1
# **	Power / Exponent	Raises a number to a power	2 ** 8	256

# Think of modulo like splitting water between bottles.
#  You have 25 glasses of water to fill into bottles that hold 8 glasses each.
#  25 // 8 tells you you can fill 3 full bottles. 25 % 8 tells you 1 glass is left over.
#  Together, they tell you the complete picture.