## CHECKING THE TYPE OF A VARIABLE

# Python has a built-in tool called type() that tells you what kind of data a variable holds.
#  You will use this when you are debugging your programs and need to confirm what Python thinks
#  something is.

steps = 9200
body_weight = 64.6
skill = "Tilling"
cold_shower = True

print(type(steps))
print(type(body_weight))
print(type(skill))
print(type(cold_shower))
