# A variable is a named container that holds a value.
#  You give it a name, you put a value inside it, and you can use that name anywhere in your program 
# to refer to that value.

# You have a jar labelled "steps". You put 9200 into it. Later, any time your program needs to know today's steps,
#  it goes to the jar labelled "steps" and reads what is inside.
#  If tomorrow you walked 10,400 steps, you just put a new number into the same jar.
#  The label stays the same. The contents change.

steps = 9200
water_glasses = 8
fasting = True
name = "Amerix Student"

print(steps)
print(water_glasses)
print(fasting)
print(name)

# The equals sign in Python does not mean "these two things are equal". 
# It means "store this value into this name".
#  You are giving Python an instruction: put 9200 into the container called steps.

